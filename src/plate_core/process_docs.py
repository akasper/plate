"""Remote PLATE process docs pointer and local fallback (#1511 / Epic #1508)."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from . import __version__ as _INSTALLED_VERSION
from .payload_surface import PLATE_DOCS_SUBDIRS

DEFAULT_PROCESS_DOCS_BASE_URL = "https://plateprocess.dev"
DEFAULT_PROCESS_DOCS_MCP_URL = "https://plateprocess.dev/mcp"

PROCESS_SUMMARY_REL = "docs/plate/PROCESS_SUMMARY.md"
CUSTOM_ENDPOINT_GUIDE_REL = "docs/migration/custom-process-docs-endpoint.md"
LEGACY_COPY_MIGRATION_REL = "docs/migration/process-docs-service.md"

ALLOWED_PROCESS_DOCS_KEYS = frozenset({"base_url", "mcp_url", "version"})

GOALS_WIKI_PAYLOAD_REL = "docs/wiki/Goals.md"
PROCESS_SUMMARY_GENERATED_MARKER = "Generated by `plate_core.process_docs`"
PROCESS_SUMMARY_GENERATED_SUFFIX = (
    "for offline use; not a substitute for the full guide set."
)

_LEGACY_DOC_MARKERS: tuple[tuple[str, ...], ...] = (
    tuple(f"docs/{subdir}/" for subdir in sorted(PLATE_DOCS_SUBDIRS)),
    ("docs/plate/agents/", "docs/plate/bootstrap/", "docs/plate/design/"),
)


def installed_plate_release_tag() -> str:
    """Return the git-style tag PLATE process docs use for this plate-core build."""
    ver = str(_INSTALLED_VERSION).strip()
    if ver.startswith("v"):
        return ver
    return f"v{ver}"


def default_process_docs_config() -> dict[str, str]:
    return {
        "base_url": DEFAULT_PROCESS_DOCS_BASE_URL,
        "mcp_url": DEFAULT_PROCESS_DOCS_MCP_URL,
        "version": installed_plate_release_tag(),
    }


def validate_process_docs_config(section: Any) -> None:
    from .plate_config import PlateConfigError

    if section is None:
        return
    if not isinstance(section, dict):
        raise PlateConfigError("'process_docs' must be an object if present")
    unknown = sorted(set(section) - ALLOWED_PROCESS_DOCS_KEYS)
    if unknown:
        raise PlateConfigError(
            f"unknown process_docs keys: {', '.join(unknown)}"
        )
    for key in ("base_url", "mcp_url", "version"):
        val = section.get(key)
        if val is None:
            continue
        if not isinstance(val, str) or not val.strip():
            raise PlateConfigError(f"process_docs.{key} must be a non-empty string if present")


def build_process_summary_markdown(
    *,
    base_url: str,
    mcp_url: str,
    version: str,
) -> str:
    base = base_url.rstrip("/")
    return f"""# PLATE process — local fallback summary

Full PLATE process documentation is served remotely so adopters do not copy large
guide trees into this repository. When the service is reachable, agents and humans
should prefer the hosted site and MCP tools.

| Surface | URL |
|---|---|
| Website | {base}/ |
| MCP | {mcp_url} |
| Pinned PLATE version | `{version}` |

## MCP (read-only)

Connect an MCP client to `{mcp_url}` and use:

- `list_docs(version)` — doc paths and titles (`version` = `{version}` or `latest`)
- `get_doc(path, version)` — one document body
- `search_docs(query, version)` — keyword search with snippets

## When the endpoint is unreachable

1. Use this file for the adoption loop reminders below.
2. Retry the website or MCP after network or hosting issues clear.
3. If you fork or self-host docs, override `process_docs` in `.plate` (see
   `{CUSTOM_ENDPOINT_GUIDE_REL}` on the default site after deploy).

## Core loop (short)

| Issue type | Agent must |
|---|---|
| Feature | Tests + `.agentic/releases/` fragment + PR to integration base + human review |
| Bug | Reproduce + regression test + `Closes #N` |
| Hardening | Tests/reliability only + hardening fragment |
| Documentation / Research / Design / Question | Durable artifact under `docs/` + PR |
| Task | `<!-- PLATE-TASK-CLOSED -->` comment when human-only work finishes |

**Never** self-merge Feature/Bug/Hardening/Documentation PRs unless autonomous mode
eligibility is fully met. Resolve agent review threads before human approval.

**Authoritative source:** `{base}/` (version `{version}`) and repository `AGENTS.md`
for repo-specific rules.

Generated by `plate_core.process_docs` for offline use; not a substitute for the full guide set.
"""


def is_default_process_docs_endpoint(section: dict[str, str]) -> bool:
    base = (section.get("base_url") or DEFAULT_PROCESS_DOCS_BASE_URL).rstrip("/")
    mcp = section.get("mcp_url") or DEFAULT_PROCESS_DOCS_MCP_URL
    return (
        base == DEFAULT_PROCESS_DOCS_BASE_URL.rstrip("/")
        and mcp == DEFAULT_PROCESS_DOCS_MCP_URL
    )


def is_generated_process_summary(text: str) -> bool:
    return PROCESS_SUMMARY_GENERATED_MARKER in text


def has_local_process_summary_edits(text: str) -> bool:
    """True when the fallback summary is not a pristine PLATE-generated file."""
    if not is_generated_process_summary(text):
        return True
    tail = text.split(PROCESS_SUMMARY_GENERATED_MARKER, 1)[1].strip()
    return tail != PROCESS_SUMMARY_GENERATED_SUFFIX


def detect_legacy_copied_plate_guides(repo_root: Path) -> list[str]:
    """Return repo-relative paths proving older imports copied PLATE guides locally."""
    root = Path(repo_root)
    found: list[str] = []
    docs = root / "docs"
    if not docs.is_dir():
        return found
    for subdir in PLATE_DOCS_SUBDIRS:
        for candidate in (docs / subdir, docs / "plate" / subdir):
            if candidate.is_dir() and any(candidate.iterdir()):
                rel = candidate.relative_to(root).as_posix() + "/"
                if rel not in found:
                    found.append(rel)
    for rel in ("docs/agents/", "docs/bootstrap/", "docs/plate/agents/"):
        p = root.joinpath(*rel.split("/"))
        if p.is_dir():
            found.append(rel)
    return sorted(found)


def _read_plate_json(path: Path) -> dict[str, Any]:
    raw = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(raw, dict):
        raise ValueError(".plate must be an object")
    return raw


def sync_process_docs_in_plate(
    plate_path: Path,
    *,
    apply: bool,
    installed_tag: str | None = None,
) -> tuple[bool, dict[str, str]]:
    """Merge ``process_docs`` defaults and bump ``version`` when apply is true.

    Returns ``(changed, merged_process_docs)``.
    """
    tag = installed_tag or installed_plate_release_tag()
    defaults = default_process_docs_config()
    defaults["version"] = tag

    if not plate_path.is_file():
        return False, defaults

    data = _read_plate_json(plate_path)
    before = json.dumps(data.get("process_docs"), sort_keys=True)
    section = data.get("process_docs")
    if not isinstance(section, dict):
        section = {}
    merged = {**defaults, **{k: v for k, v in section.items() if k in ALLOWED_PROCESS_DOCS_KEYS}}
    stored_version = section.get("version")
    explicit_version = (
        isinstance(stored_version, str) and bool(stored_version.strip())
    )
    if is_default_process_docs_endpoint(merged) or not explicit_version:
        merged["version"] = tag
    else:
        merged["version"] = stored_version.strip()
    data["process_docs"] = merged
    after = json.dumps(merged, sort_keys=True)
    changed = before != after
    if apply and changed:
        plate_path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    return changed, merged


def seed_process_docs_artifacts(
    target: Path,
    *,
    apply: bool,
    process_docs: dict[str, str],
    legacy_guide_dirs: list[str] | None = None,
) -> tuple[list[str], list[str], list[str], list[str]]:
    """Write fallback summary and sync ``.plate`` pointer.

    Returns ``(would_create_or_update, created_or_updated, notes, preserved)``.
    """
    would: list[str] = []
    done: list[str] = []
    notes: list[str] = []
    preserved: list[str] = []

    plate_path = target / ".plate"
    plate_changed, merged = sync_process_docs_in_plate(plate_path, apply=apply)
    process_docs = {**process_docs, **merged}

    summary_path = target / PROCESS_SUMMARY_REL
    summary_text = build_process_summary_markdown(
        base_url=process_docs["base_url"],
        mcp_url=process_docs["mcp_url"],
        version=process_docs["version"],
    )
    if summary_path.is_file():
        existing = summary_path.read_text(encoding="utf-8")
        if existing == summary_text:
            pass
        elif has_local_process_summary_edits(existing):
            preserved.append(PROCESS_SUMMARY_REL)
            notes.append(
                f"Preserved local edits to {PROCESS_SUMMARY_REL} (not overwritten on import/upgrade)."
            )
        else:
            would.append(PROCESS_SUMMARY_REL)
            if apply:
                summary_path.parent.mkdir(parents=True, exist_ok=True)
                summary_path.write_text(summary_text, encoding="utf-8")
                done.append(PROCESS_SUMMARY_REL)
    else:
        would.append(PROCESS_SUMMARY_REL)
        if apply:
            summary_path.parent.mkdir(parents=True, exist_ok=True)
            summary_path.write_text(summary_text, encoding="utf-8")
            done.append(PROCESS_SUMMARY_REL)
    if plate_changed or not plate_path.is_file():
        would.append(".plate process_docs")
        if apply and plate_path.is_file() and plate_changed:
            done.append(".plate process_docs")

    if legacy_guide_dirs:
        joined = ", ".join(legacy_guide_dirs[:5])
        suffix = " …" if len(legacy_guide_dirs) > 5 else ""
        notes.append(
            "Legacy copied PLATE guides were left in place "
            f"({joined}{suffix}). Full guides: {process_docs['base_url'].rstrip('/')}/ "
            f"(version {process_docs['version']}). "
            f"Optional cleanup: see {LEGACY_COPY_MIGRATION_REL} on the hosted docs."
        )
    return would, done, notes, preserved


def reconcile_process_docs_artifacts(
    repo_root: Path | str,
    *,
    apply: bool,
) -> tuple[list[str], list[str], list[str], list[str]]:
    """Sync pointer and fallback on disk (import, upgrade, or explicit repair)."""
    root = Path(repo_root)
    legacy_dirs = detect_legacy_copied_plate_guides(root)
    plate_path = root / ".plate"
    _, merged = sync_process_docs_in_plate(plate_path, apply=apply)
    return seed_process_docs_artifacts(
        root,
        apply=apply,
        process_docs=merged,
        legacy_guide_dirs=legacy_dirs,
    )


def is_plate_payload_doc_path(rel: str) -> bool:
    """True when a template payload relative path is a PLATE guide under docs/."""
    if not rel.startswith("docs/"):
        return False
    return rel != GOALS_WIKI_PAYLOAD_REL